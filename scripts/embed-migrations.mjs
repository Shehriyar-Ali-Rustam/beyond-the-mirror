// Embeds supabase/migrations/*.sql into the app so the running site can apply
// them without reading files from disk (see src/lib/db-status.ts).
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { migrationsFromDisk } from "./migrations-from-disk.mjs";

const migrations = await migrationsFromDisk();
const out = path.join(process.cwd(), "src", "lib", "generated", "migrations.ts");
await mkdir(path.dirname(out), { recursive: true });
await writeFile(
  out,
  `// Generated by scripts/embed-migrations.mjs — do not edit. Source: supabase/migrations/\n` +
    `export const MIGRATIONS: { file: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`[migrate] Embedded ${migrations.length} migration(s).`);
